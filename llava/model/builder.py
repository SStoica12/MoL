import os
import warnings
import shutil
import json
from safetensors.torch import load_file as safe_load_file
from transformers import AutoTokenizer, AutoModelForCausalLM, AutoConfig, BitsAndBytesConfig
import torch
from llava.model import *
from llava.constants import DEFAULT_IMAGE_PATCH_TOKEN, DEFAULT_IM_START_TOKEN, DEFAULT_IM_END_TOKEN
from safetensors.torch import load_file
from llava.model.language_model.llava_llama import RouterLlavaLlamaForCausalLM
from llava.model.language_model.llava_mpt import RouterLlavaMptForCausalLM
from llava.model.router import Router

def load_pretrained_model_router(model_path, model_base, model_name, load_8bit=False, load_4bit=False, device_map="auto", device="cuda", use_flash_attn=False, num_layers_to_choose=1, router_alpha=0.01,**kwargs):
    print(f"\n      num_layers_to_choose should be 1: {num_layers_to_choose == 1} and router_alpha should be 0.01 : {router_alpha == 0.01} and device_map {device_map}")
    kwargs = {"device_map": device_map, **kwargs}

    if device != "cuda":
        kwargs['device_map'] = {"": device}

    if load_8bit:
        kwargs['load_in_8bit'] = True
    elif load_4bit:
        kwargs['load_in_4bit'] = True
        kwargs['quantization_config'] = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_compute_dtype=torch.float16,
            bnb_4bit_use_double_quant=True,
            bnb_4bit_quant_type='nf4'
        )
    else:
        kwargs['torch_dtype'] = torch.float16

    if use_flash_attn:
        kwargs['attn_implementation'] = 'flash_attention_2'

    if 'llava' in model_name.lower():
        # Load LLaVA model
        if 'lora' in model_name.lower() and model_base is None:
            warnings.warn('There is `lora` in model name but no `model_base` is provided. If you are loading a LoRA model, please provide the `model_base` argument. Detailed instruction: https://github.com/haotian-liu/LLaVA#launch-a-model-worker-lora-weights-unmerged.')
        if 'lora' in model_name.lower() and model_base is not None:
            from llava.model.language_model.llava_llama import LlavaConfig
            lora_cfg_pretrained = LlavaConfig.from_pretrained(model_path)
            tokenizer = AutoTokenizer.from_pretrained(model_base, use_fast=False)
            print('Loading LLaVA from base model...')
            model = RouterLlavaLlamaForCausalLM.from_pretrained(model_base, low_cpu_mem_usage=True, config=lora_cfg_pretrained, **kwargs)
            token_num, tokem_dim = model.lm_head.out_features, model.lm_head.in_features
            if model.lm_head.weight.shape[0] != token_num:
                model.lm_head.weight = torch.nn.Parameter(torch.empty(token_num, tokem_dim, device=model.device, dtype=model.dtype))
                model.model.embed_tokens.weight = torch.nn.Parameter(torch.empty(token_num, tokem_dim, device=model.device, dtype=model.dtype))

            print('Loading additional LLaVA weights...')
            if os.path.exists(os.path.join(model_path, 'non_lora_trainables.bin')):
                non_lora_trainables = torch.load(os.path.join(model_path, 'non_lora_trainables.bin'), map_location='cpu')
            else:
                # this is probably from HF Hub
                from huggingface_hub import hf_hub_download
                def load_from_hf(repo_id, filename, subfolder=None):
                    cache_file = hf_hub_download(
                        repo_id=repo_id,
                        filename=filename,
                        subfolder=subfolder)
                    return torch.load(cache_file, map_location='cpu')
                non_lora_trainables = load_from_hf(model_path, 'non_lora_trainables.bin')
            non_lora_trainables = {(k[11:] if k.startswith('base_model.') else k): v for k, v in non_lora_trainables.items()}
            if any(k.startswith('model.model.') for k in non_lora_trainables):
                non_lora_trainables = {(k[6:] if k.startswith('model.') else k): v for k, v in non_lora_trainables.items()}
            model.load_state_dict(non_lora_trainables, strict=False)

            from peft import PeftModel
            print('Loading LoRA weights...')
            model = PeftModel.from_pretrained(model, model_path)
            print('Merging LoRA weights...')
            model = model.merge_and_unload()
            print('Model is loaded...')
        elif model_base is not None:
            # this may be mm projector only
            print('Loading LLaVA from base model...')
            if 'mpt' in model_name.lower():
                if not os.path.isfile(os.path.join(model_path, 'configuration_mpt.py')):
                    shutil.copyfile(os.path.join(model_base, 'configuration_mpt.py'), os.path.join(model_path, 'configuration_mpt.py'))
                tokenizer = AutoTokenizer.from_pretrained(model_base, use_fast=True)
                cfg_pretrained = AutoConfig.from_pretrained(model_path, trust_remote_code=True)
                model = RouterLlavaMptForCausalLM.from_pretrained(model_base, low_cpu_mem_usage=True, config=cfg_pretrained, **kwargs)
            else:
                tokenizer = AutoTokenizer.from_pretrained(model_base, use_fast=False)
                cfg_pretrained = AutoConfig.from_pretrained(model_path)
                model = RouterLlavaLlamaForCausalLM.from_pretrained(model_base, low_cpu_mem_usage=True, config=cfg_pretrained, **kwargs)

            mm_projector_weights = torch.load(os.path.join(model_path, 'mm_projector.bin'), map_location='cpu')
            mm_projector_weights = {k: v.to(torch.float16) for k, v in mm_projector_weights.items()}
            model.load_state_dict(mm_projector_weights, strict=False)
        else:
            if 'mpt' in model_name.lower():
                tokenizer = AutoTokenizer.from_pretrained(model_path, use_fast=True)
                model = RouterLlavaMptForCausalLM.from_pretrained(model_path, low_cpu_mem_usage=True, **kwargs)
            elif 'mistral' in model_name.lower():
                tokenizer = AutoTokenizer.from_pretrained(model_path)
                model = RouterLlavaMptForCausalLM.from_pretrained(
                    model_path,
                    low_cpu_mem_usage=True,
                    **kwargs
                )
            else:
                tokenizer = AutoTokenizer.from_pretrained(model_path, use_fast=False)
                model = RouterLlavaLlamaForCausalLM.from_pretrained(
                    model_path,
                    low_cpu_mem_usage=True,
                    **kwargs
                )
    else:
        # Load language model
        if model_base is not None:
            # PEFT model
            from peft import PeftModel
            tokenizer = AutoTokenizer.from_pretrained(model_base, use_fast=False)
            model = AutoModelForCausalLM.from_pretrained(model_base, low_cpu_mem_usage=True, **kwargs)
            print(f"Loading LoRA weights from {model_path}")
            model = PeftModel.from_pretrained(model, model_path)
            print(f"Merging weights")
            model = model.merge_and_unload()
            print('Convert to FP16...')
            model.to(torch.float16)
        else:
            use_fast = False
            if 'mpt' in model_name.lower():
                tokenizer = AutoTokenizer.from_pretrained(model_path, use_fast=True)
                model = AutoModelForCausalLM.from_pretrained(model_path, low_cpu_mem_usage=True, trust_remote_code=True, **kwargs)
            else:
                tokenizer = AutoTokenizer.from_pretrained(model_path, use_fast=False)
                model = AutoModelForCausalLM.from_pretrained(model_path, low_cpu_mem_usage=True, **kwargs)

    image_processor = None

    if 'llava' in model_name.lower():
        mm_use_im_start_end = getattr(model.config, "mm_use_im_start_end", False)
        mm_use_im_patch_token = getattr(model.config, "mm_use_im_patch_token", True)
        if mm_use_im_patch_token:
            tokenizer.add_tokens([DEFAULT_IMAGE_PATCH_TOKEN], special_tokens=True)
        if mm_use_im_start_end:
            tokenizer.add_tokens([DEFAULT_IM_START_TOKEN, DEFAULT_IM_END_TOKEN], special_tokens=True)
        model.resize_token_embeddings(len(tokenizer))

        vision_tower = model.get_vision_tower()
        if not vision_tower.is_loaded:
            vision_tower.load_model(device_map=device_map)
        vision_tower.to(device=device, dtype=torch.float16)
        image_processor = vision_tower.image_processor

        # print(vision_tower)
        # import sys; sys.exit(0)
        # load the router        
        image_size = vision_tower.vision_tower.config.image_size
        patch_size = vision_tower.vision_tower.config.patch_size
        hidden_size = vision_tower.vision_tower.config.hidden_size
        # print("patch_size: ", patch_size)
        # print("hidden_size: ", hidden_size)
        num_image_tokens = (image_size // patch_size)**2 + 1
        assert num_image_tokens != 1
        print("vision_tower.dtype : ", vision_tower.dtype)
        # print("num_image_tokens:", num_image_tokens)
        router_weights = torch.zeros((num_image_tokens, hidden_size)).to(dtype=vision_tower.dtype, device=device)
        assert router_weights.is_cuda
        # print("model.config.mm_vision_select_feature: ", model.config.mm_vision_select_feature) # patch
        model.router = Router(model.config, router_weights, model.config.mm_vision_select_feature, router_alpha)
        model.router.num_layers_to_choose = num_layers_to_choose
        model.router.requires_grad_(False) # we need to learn the router

        # overwrite the router weights
        print("♻️  Overwriting Router weights with custom finetuned weights...")
        index_path = os.path.join(model_path, "model.safetensors.index.json")
        if not os.path.isfile(index_path):
            raise FileNotFoundError(f"Missing: {index_path}")

        with open(index_path, "r") as f:
            index = json.load(f)

        weight_map = index["weight_map"]

        # find router key in the big model checkpoint
        router_keys = [k for k in weight_map.keys() if "router" in k.lower() and ("weight" in k.lower())]
        print("router_keys : ", router_keys)
        assert len(router_keys) == 1
        shard_file = weight_map[router_keys[0]]
        shard_path = os.path.join(model_path, shard_file)
        print(f"\n    Loaded checkpoint path {shard_path}")
        shard_weights = safe_load_file(shard_path)  # loads CPU tensors
        router_state_dict = {}
        for key, value in shard_weights.items():
                # We filter for keys belonging to the router
                if "router" in key:
                    key = key.replace("router.", "")  # need just weights
                    assert key == "weights"
                    router_state_dict[key] = value
        # 3. Load these weights into the model
        #    strict=False is crucial because we are only loading the vision subset
        if len(router_state_dict) > 0:
            missing, unexpected = model.router.load_state_dict(router_state_dict, strict=False)
            if len(missing) != 0 or len(unexpected) != 0:
                print("missing: ", missing)
                print("unexpected: ", unexpected)
                # print(missing, unexpected)
                import sys; sys.exit(0)
            else:
                print(f"✅ Successfully restored {len(router_state_dict)} custom router keys.")
        else:
            print("⚠️  Warning: No custom router keys found in shards.")
        print("model.router_weights: ", model.router.weights)
        # model.router.weights.data.to(torch.bfloat16)
        # # import pdb; pdb.set_trace()
        # import glob
        # from safetensors.torch import load_file
        
        # # Locate all safetensor shards
        # shard_files = glob.glob(os.path.join(model_path, "*.safetensors"))
        
        # router_state_dict = {}
        
        # # 2. Iterate through shards and collect ONLY vision tower keys
        # for shard in shard_files:
        #     shard_weights = load_file(shard)
        #     for key, value in shard_weights.items():
        #         # We filter for keys belonging to the router
        #         if "router" in key:
        #             router_state_dict[key] = value
        
        # # 3. Load these weights into the model
        # #    strict=False is crucial because we are only loading the vision subset
        # if len(router_state_dict) > 0:
        #     model.router.load_state_dict(router_state_dict, strict=False)
        #     print(f"✅ Successfully restored {len(router_state_dict)} custom router keys.")
        # else:
        #     print("⚠️  Warning: No custom router keys found in shards.")

    if hasattr(model.config, "max_sequence_length"):
        context_len = model.config.max_sequence_length
    else:
        context_len = 2048
    
    return tokenizer, model, image_processor, context_len


